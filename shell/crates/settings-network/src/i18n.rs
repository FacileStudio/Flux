static CHOSEN: OnceLock<&'static Text> = OnceLock::new();

/// The strings for `code`, an ISO 639-1 language.
pub fn for_code(code: &str) -> &'static Text {
    if code.starts_with("fr") {
        &FR
    } else {
        &EN
    }
}

/// The strings for the user's language, from the usual locale variables, or
/// from the `<lang>:` prefix of `FLUX_NETWORK_PREVIEW` in a preview.
pub fn text() -> &'static Text {
    CHOSEN.get_or_init(|| {
        let preview = std::env::var("FLUX_NETWORK_PREVIEW")
            .ok()
            .and_then(|name| name.split_once(':').map(|(code, _)| code.to_string()));
        let code = preview
            .into_iter()
            .chain(
                ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"]
                    .iter()
                    .filter_map(|name| std::env::var(name).ok()),
            )
            .find(|value| !value.is_empty())
            .unwrap_or_default();
        for_code(&code)
    })
}
