/// Whether the session speaks French, from `FLUX_LANG`, then the usual
/// locale variables.
pub fn french() -> bool {
    ["FLUX_LANG", "LC_ALL", "LC_MESSAGES", "LANG"]
        .iter()
        .find_map(|key| std::env::var(key).ok().filter(|value| !value.is_empty()))
        .is_some_and(|value| value.starts_with("fr"))
}

pub fn text() -> &'static Text {
    if french() {
        &FR
    } else {
        &EN
    }
}

/// Replace `{key}` in `template` with `value`.
pub fn fill(template: &str, key: &str, value: &str) -> String {
    template.replace(&format!("{{{key}}}"), value)
}
